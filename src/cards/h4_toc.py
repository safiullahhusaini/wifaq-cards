# Pages the teacher announces in class come from another edition (e.g. كتاب الشفعة = 1637, فصل في الجنين = 1992,
# باب في اعتبار حالة القتل = 1956, the Qasama passage on colleagues' 1926 = 2056). Not usable directly.


def where(page):
    """-> (kitab, bab_or_None, fasl_or_None) for a colleagues' page."""
    kitab = bab = fasl = None
    for level, title, p in TOC:
        if p > page:
            break
        if level == 1:
            kitab, bab, fasl = title, None, None
        elif level == 2:
            bab, fasl = title, None
        else:
            fasl = title
    return kitab, bab, fasl
